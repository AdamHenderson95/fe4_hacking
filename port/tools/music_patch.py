"""Builds the MSU-1 music patch (src/fe4music_patch.h and the kit's copy in fe4msu.py).

FE4 asks for a song by writing its number to $04BA; the sound script engine ($80:9677) starts the song's
script (upload the music data, then tell the sound chip to play it).  The patch hooks two places:
  $80:968A  a new song for slot 0: if an MSU-1 chip is there and has this track, play it, stop the game's
            music and end the song's script; otherwise stop the MSU-1 track and go on as before.
  $80:8FD5  a sound command joins the queue for the sound chip: E0-E2 (fade the music out) also fade
            the MSU-1 track (volume 0; the port fades it smoothly).
The new code goes in bank $80's empty end ($80:FD00).
"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from asm import assemble, snes_to_file

ORG = 0x80FD00
SRC = r'''
.m 0
.x 0
music_req:                ; from $80:968A, A = song (16-bit), X = slot * 2
    STA $04C6,X
    AND #$00FF
    CPX #$0000
    BNE plain
    PHA
    LDA $002002
    CMP #$2D53            ; "S-"
    BNE nomsu
    LDA $002004
    CMP #$534D            ; "MS"
    BNE nomsu
    LDA $002006
    CMP #$3155            ; "U1"
    BNE nomsu
    LDA $01,S
    STA $002004           ; track number: $2004, then $2005 (loads it)
    SEP #$20
wait:
    LDA $002000
    BITI #$40              ; audio busy
    BNE wait
    BITI #$08              ; track missing
    BNE miss
    LDA #$FF
    STA $002006           ; full volume
    LDA #$03
    STA $002007           ; play, repeat
    REP #$20
    LDA $04F6
    AND #$0002            ; the game's music is playing: stop it
    BEQ stopped
    LDA #$00F8
    JSL $808FA3
stopped:
    SEP #$20
    STZ $04EB             ; nothing to resume when the sound option turns music back on
    REP #$20
    PLA
    LDA #$96EF            ; return to the end of the song's script ($80:96F0) with A = 0
    STA $01,S
    LDA #$0000
    RTL
miss:
.m 1
    LDA #$00
    STA $002007           ; no file for this song: stop the MSU-1 track
    REP #$20
.m 0
nomsu:
    PLA
plain:
    RTL

.m 0
.x 0
music_cmd:                ; from $80:8FD5: a sound command joins the queue (value pushed under our return)
    LDA $04,S
    STA $04D8,X           ; what the game does here
    TAX
    AND #$00FF
    CMP #$00E0
    BCC done
    CMP #$00E3
    BCS done
    LDA $002002
    CMP #$2D53
    BNE done
    SEP #$20
    LDA $002000
    AND #$10
    BEQ done8
    LDA #$00
    STA $002006           ; fade out
done8:
    REP #$20
done:
    LDA $02,S             ; take the pushed value off the stack: move the return address up 2 bytes
    STA $04,S
    SEP #$20
    LDA $01,S
    STA $03,S
    REP #$20
    PLA
    TXA                   ; A = the command, as after the game's PLA
    RTL
'''

def build():
    code, labels = assemble(SRC, ORG)
    def jsl(t): return bytes([0x22, t & 0xff, (t >> 8) & 0xff, t >> 16, 0xEA, 0xEA])
    patches = [
        (snes_to_file(0x80968A), bytes.fromhex('9DC60429FF00'), jsl(labels['music_req'])),
        (snes_to_file(0x808FD5), bytes.fromhex('689DD804'), jsl(labels['music_cmd'])[:4]),
        (snes_to_file(ORG), bytes(len(code)), code),
    ]
    return patches

if __name__ == '__main__':
    P = build()
    here = os.path.dirname(os.path.abspath(__file__))
    out = ['// Generated by tools/music_patch.py: MSU-1 music hooks (see that file).', '#ifndef FE4MUSIC_PATCH_H',
           '#define FE4MUSIC_PATCH_H', '#include "fe4patch.h"']
    for i, (off, o, n) in enumerate(P):
        out.append('static const unsigned char FE4_MUSIC_o%d[] = { %s };' % (i, ', '.join('0x%02X' % b for b in o)))
        out.append('static const unsigned char FE4_MUSIC_n%d[] = { %s };' % (i, ', '.join('0x%02X' % b for b in n)))
    out.append('static const Fe4Patch FE4_MUSIC[] = {')
    for i, (off, o, n) in enumerate(P):
        out.append('  { 0x%06X, %d, %d, FE4_MUSIC_o%d, FE4_MUSIC_n%d },' % (off, len(o), len(n), i, i))
    out.append('  { 0, 0, 0, 0, 0 }\n};\n#endif\n')
    open(os.path.join(here, '..', 'src', 'fe4music_patch.h'), 'w').write('\n'.join(out))
    kit = os.path.join(here, '..', '..', 'kit', 'fe4msu_data.py')
    lines = ['"""Generated by port/tools/music_patch.py: the MSU-1 music hooks (file offset, original, new)."""', 'PATCHES = [']
    for off, o, n in P:
        lines.append("    (0x%06X, bytes.fromhex('%s'), bytes.fromhex('%s'))," % (off, o.hex(), n.hex()))
    lines.append(']\n')
    open(kit, 'w').write('\n'.join(lines))
    for off, o, n in P: print('%06X %d bytes' % (off, len(n)))
